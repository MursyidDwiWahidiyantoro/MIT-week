<script lang="ts">
  import { t } from '$lib/i18n/index.svelte';
  import Button from '$lib/components/ui/Button.svelte';
  import Icon from '$lib/components/ui/Icon.svelte';
  import forensicQuiz from '$lib/data/forensic-quiz.json';

  const modus = [
    {
      id: 'ai',
      tone: 'yellow',
      icon: 'sparkle',
      title: 'edu.m.ai.title',
      body: 'edu.m.ai.body'
    },
    {
      id: 'judul',
      tone: 'soft',
      icon: 'image',
      title: 'edu.m.judul.title',
      body: 'edu.m.judul.body'
    },
    {
      id: 'shortlink',
      tone: 'lime',
      icon: 'link',
      title: 'edu.m.shortlink.title',
      body: 'edu.m.shortlink.body'
    }
  ] as const;

  const questions = [
    {
      id: 'q1',
      question: 'edu.q1',
      options: [
        { id: 'a', text: 'edu.q1.a', correct: false },
        { id: 'b', text: 'edu.q1.b', correct: true },
        { id: 'c', text: 'edu.q1.c', correct: false }
      ],
      explain: 'edu.q1.explain'
    },
    {
      id: 'q2',
      question: 'edu.q2',
      options: [
        { id: 'a', text: 'edu.q2.a', correct: true },
        { id: 'b', text: 'edu.q2.b', correct: false },
        { id: 'c', text: 'edu.q2.c', correct: false }
      ],
      explain: 'edu.q2.explain'
    },
    {
      id: 'q3',
      question: 'edu.q3',
      options: [
        { id: 'a', text: 'edu.q3.a', correct: false },
        { id: 'b', text: 'edu.q3.b', correct: true },
        { id: 'c', text: 'edu.q3.c', correct: false }
      ],
      explain: 'edu.q3.explain'
    }
  ] as const;

  let answers = $state<Record<string, string>>({});
  let checked = $state(false);

  const score = $derived(
    questions.filter((q) => q.options.find((o) => o.id === answers[q.id])?.correct).length
  );

  // PRD F7: three synthetic images with the ELA heat map AMBA computed for
  // each (generated by backend/cmd/gendemo, shipped as static files).
  type Guess = 'asli' | 'diedit' | 'belum-pasti';
  const GUESSES: Guess[] = ['asli', 'diedit', 'belum-pasti'];
  const forensic = forensicQuiz.items as Array<{ id: string; image: string; ela: string; answer: Guess }>;
  let guesses = $state<Record<string, Guess | undefined>>({});
  let revealed = $state<Record<string, boolean>>({});

  function reset(): void {
    answers = {};
    checked = false;
  }
</script>

<svelte:head>
  <title>{t('edu.title')}</title>
  <meta name="description" content={t('edu.description')} />
</svelte:head>

<section class="head">
  <p class="eyebrow">{t('edu.eyebrow')}</p>
  <h1 class="h1">{t('edu.h1')}</h1>
  <p class="lede">{t('edu.lede')}</p>
</section>

<section aria-labelledby="modus-title">
  <h2 class="h2" id="modus-title">{t('edu.modusTitle')}</h2>
  <div class="grid">
    {#each modus as m (m.id)}
      <article class="mode card lift mode--{m.tone}">
        <span class="icon" aria-hidden="true"><Icon name={m.icon} size={28} /></span>
        <h3>{t(m.title)}</h3>
        <p>{t(m.body)}</p>
      </article>
    {/each}
  </div>
</section>

<section class="forensic" aria-labelledby="forensic-title">
  <h2 class="h2" id="forensic-title">{t('fq.title')}</h2>
  <p class="quiz-lede">{t('fq.lede')}</p>
  <div class="forensic-grid">
    {#each forensic as item, i (item.id)}
      <article class="f-item card lift">
        <img class="f-img" src={item.image} alt={t('fq.imageAlt', { n: i + 1 })} width="360" height="480" loading="lazy" />
        <div class="f-body">
          <p class="q-legend" id={`fq-${item.id}`}>
            <span class="q-num" aria-hidden="true">{i + 1}</span>{t('fq.question')}
          </p>
          <div class="f-options" role="radiogroup" aria-labelledby={`fq-${item.id}`}>
            {#each GUESSES as g (g)}
              <label class="option">
                <input type="radio" name={`fq-${item.id}`} value={g} bind:group={guesses[item.id]} />
                <span>{t(`fq.opt.${g}`)}</span>
              </label>
            {/each}
          </div>
          <button
            class="btn btn--quiet btn--sm"
            type="button"
            aria-expanded={!!revealed[item.id]}
            aria-controls={`fq-panel-${item.id}`}
            disabled={!guesses[item.id]}
            onclick={() => (revealed = { ...revealed, [item.id]: !revealed[item.id] })}
          >
            <Icon name="image" size={16} /> {revealed[item.id] ? t('fq.hide') : t('fq.reveal')}
          </button>
          {#if revealed[item.id]}
            <div class="f-reveal" id={`fq-panel-${item.id}`}>
              <figure>
                <img src={item.ela} alt={t('fq.elaAlt', { n: i + 1 })} width="360" height="480" />
                <figcaption>{t('fq.ela')}</figcaption>
              </figure>
              <p class="f-verdict" role="status">
                {guesses[item.id] === item.answer ? t('fq.right') : t('fq.wrong', { answer: t(`fq.opt.${item.answer}`) })}
              </p>
              <p class="explain">{t(`fq.explain.${item.answer}`)}</p>
            </div>
          {/if}
        </div>
      </article>
    {/each}
  </div>
</section>

<section class="quiz" aria-labelledby="kuis-title">
  <h2 class="h2" id="kuis-title">{t('edu.quizTitle')}</h2>
  <p class="quiz-lede">{t('edu.quizLede')}</p>

  {#each questions as q, i (q.id)}
    <div class="q card lift" role="radiogroup" aria-labelledby={`q-label-${q.id}`}>
      <p class="q-legend" id={`q-label-${q.id}`}>
        <span class="q-num" aria-hidden="true">{i + 1}</span>
        {t(q.question)}
      </p>
      {#each q.options as option (option.id)}
        <label
          class="option"
          class:correct={checked && option.correct}
          class:wrong={checked && answers[q.id] === option.id && !option.correct}
        >
          <input type="radio" name={q.id} value={option.id} bind:group={answers[q.id]} disabled={checked} />
          <span>{t(option.text)}</span>
          {#if checked && option.correct}
            <span class="verdict-tag">{t('edu.correct')}</span>
          {:else if checked && answers[q.id] === option.id}
            <span class="verdict-tag">{t('edu.wrong')}</span>
          {/if}
        </label>
      {/each}
      {#if checked}
        <p class="explain">{t(q.explain)}</p>
      {/if}
    </div>
  {/each}

  <div class="actions">
    {#if !checked}
      <Button onclick={() => (checked = true)} disabled={Object.keys(answers).length < questions.length}>
        {t('edu.check')}
      </Button>
    {:else}
      <p class="result" role="status">
        <span class="result-num">{score}<span class="result-total">/{questions.length}</span></span>
        {t('edu.right')}
      </p>
      <Button variant="quiet" onclick={reset}>
        <Icon name="refresh" size={18} /> {t('edu.again')}
      </Button>
    {/if}
  </div>
</section>

